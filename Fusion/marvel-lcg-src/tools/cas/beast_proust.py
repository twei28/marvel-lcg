LAB = 'bs002'


def M(carte):
    return f"Puzzle.PutIntoPlay('{carte}', under_control=True)"


def SOUS(carte, hote=LAB):
    """Glisse CARTE sous Beast's Lab (ou un autre hote), comme apres Tech Support."""
    return f"Puzzle.PlaceUnder('{carte}', '{hote}')"


def DECK_JOUEUR(*cartes):
    """Deck du joueur = exactement ces cartes (⚠ a monter dans `declencher`, apres `main_exclusive` : `EmptyPlayerDeck` RETIRE DE LA PARTIE les cartes du deck)."""
    return ["Puzzle.EmptyPlayerDeck()", "Puzzle.CreatePlayerDeck(" + ", ".join(f"'{c}'" for c in cartes) + ")"]


