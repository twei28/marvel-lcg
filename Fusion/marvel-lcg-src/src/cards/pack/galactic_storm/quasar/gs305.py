# No Holding Back — evenement signature (QUASAR 5/16 et 6/16, x2). ATTACK. THWART.
# Cout 2, [physical].
# Hero Action (attack/thwart): Deal 3 damage to an enemy for each [physical]
#   resource you used to pay for this card. Remove 2 threat from a scheme for
#   each [mental] resource you used to pay for this card.
#
# Icones du texte relues sur l'image le 20/10/2026 : poing = [physical], noeuds
# relies = [mental] (decoupe contre les reskins Strength 67 et Genius 66 du
# meme deck, RES=RR / BB).
#
# Cartes de reference :
#  - **`47021`** Multitalented (qui est d'ailleurs dans le deck de Quasar) :
#    `effect.GetPaidResources(True)` (le joueur PRECISE ce que vaut chaque
#    joker, `AskSpecifyResources`), puis une branche `attack` et une branche
#    `thwart` choisies DANS l'operation par `ChooseAbilities(ForChoiceAbility(
#    ...).SetLabel(...).SetTarget(...))`.
#
# ⚠ Mots-pieges (PROCESSUS-CARTE etape 5) :
#  - « 3 damage ... FOR EACH [physical] » : UNE attaque de 3 x n (FAQ p.22 du
#    livret 1.2 : avec Quantum Jump et deux [mental] dont un des Bandes, « remove
#    4 threat, Quantum Jump +2, total 6 » : un seul contre de 2 x n).
#  - « resource you USED TO PAY » : les ressources depensees, pas les icones
#    imprimees sur les cartes ; un joker (Quantum Bands, Quantum Energy) compte
#    pour la couleur que le joueur lui donne (FAQ : « two P resources, one
#    generated by Quantum Bands »).
#  - aucune [physical] : pas d'attaque du tout ; aucune [mental] : pas de
#    contre (FAQ : « no threat removed, the unresolved part cannot be
#    increased » par Quantum Jump).
#  - « an enemy » / « a scheme » : une cible chacun, choisies au moment de
#    resoudre la partie concernee.


def GetAbilities() -> Sequence['Ability']:

    def sans_retenue(effect: 'Effect', message: 'Message.WhenPlayerInTurn') -> None:
        this = effect.this.CastTo(Event)
        Unused(message)

        joueur = effect.GetInitiator()
        payees = effect.GetPaidResources(True)
        physiques = payees.GetColor("R", convert_green_res=False)
        mentales = payees.GetColor("B", convert_green_res=False)
        if physiques > 0:
            joueur.ChooseAbilities(
                effect,
                AbilityFactory.ForChoiceAbility(
                    "",
                    lambda cibles: this.DealDamage(cibles, 3 * physiques, effect),
                ).SetLabel('attack')
                .SetTarget(Enemy),
            )
        if mentales > 0:
            joueur.ChooseAbilities(
                effect,
                AbilityFactory.ForChoiceAbility(
                    "",
                    lambda cibles: this.RemoveThreatFromSchemes(cibles, 2 * mentales, effect),
                ).SetLabel('thwart')
                .SetTarget(Scheme2),
            )

    return [
        AbilityFactory.WhenInYourPlayTurn(
            AbilityType.HeroAction,
            sans_retenue,
        ).SetPlay().SetLabel('attack', 'thwart'),
    ]
